const normalize = (value: string): string => value.toLowerCase().trim().replace(/[«»"\']/g, '');

// Ниша и ключевые слова → английские термины для поиска. Совпадение ищется и
// целиком, и по вхождению: «салон красоты» встречается и как «красота».
export const termsFor = (industry: string, keywords = ''): string[] => {
  const source = [industry, keywords]
    .filter(Boolean)
    .join(',')
    .split(/[,;/]|\s+и\s+/)
    .map(normalize)
    .filter(Boolean);

  const terms: string[] = [];

  for (const term of source) {
    const exact = TRANSLATION_DICTIONARY[term];

    if (exact) {
      terms.push(...exact);
      continue;
    }

    for (const [russian, english] of Object.entries(TRANSLATION_DICTIONARY)) {
      if (term.includes(russian) || russian.includes(term)) terms.push(...english);
    }
  }

  return [...new Set(terms)];
};

// Понятие → конкретные имена иконок, от точного к общему
export const expand = (term: string): string[] => [term, ...(ALIASES[term] || [])];

export const commonTerms = COMMON_TERMS;
